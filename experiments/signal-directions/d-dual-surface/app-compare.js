#!/usr/bin/env bun
/**
 * DIRECTION D — the real-app A/B runner.
 *
 * For each candidate backend it
 *   1. builds `apps/repl` with `@jsx6/signal` aliased to that direction's copied core (or unaliased,
 *      for the baseline control),
 *   2. proves the alias actually took effect by looking for an implementation marker in the bundle,
 *   3. boots the bundle headlessly in its own process and asserts what rendered, including the two
 *      asynchronous paths (`Loop` re-render, Promise-as-child),
 *   4. reports bundle size and boot time.
 *
 *   bun experiments/signal-directions/d-dual-surface/app-compare.js
 *   bun experiments/signal-directions/d-dual-surface/app-compare.js --serve=c-alien-backend
 *   bun experiments/signal-directions/d-dual-surface/app-compare.js --serve=c-alien-backend --port=5120
 *
 * The `--serve` mode is the "use it for a day" step: it starts a real static server over the built app
 * so the REPL can be clicked through on the swapped core.
 */

import { spawnSync } from 'child_process'
import { existsSync, readFileSync, writeFileSync } from 'fs'
import { join, resolve } from 'path'
import { BUILD_ROOT, ENTRIES, buildApp, bundleContains } from './app-build.js'

const HERE = import.meta.dir
const DIRS = resolve(HERE, '..')
const RESULTS = join(DIRS, 'harness/.results')
const OUT = join(DIRS, 'APP-RESULTS.md')

/** A string literal that only exists in a given implementation, used to prove the alias took effect. */
const MARKERS = {
  baseline: { needle: 'signalAlienSource', expect: false },
  'b-native-computed': { needle: 'signalStateChildren', expect: true },
  'c-alien-backend': { needle: 'signalAlienSource', expect: true },
}

const args = process.argv.slice(2)
const serveArg = args.find(a => a.startsWith('--serve'))
const serveId = serveArg ? (serveArg.includes('=') ? serveArg.split('=')[1] : 'baseline') : null
const portArg = args.find(a => a.startsWith('--port='))
const port = portArg ? Number(portArg.split('=')[1]) : 5120

const ids = serveId
  ? [serveId]
  : (args.filter(a => !a.startsWith('--')) .length
      ? args.filter(a => !a.startsWith('--'))
      : ['baseline', 'b-native-computed', 'c-alien-backend'])

const rows = []
for (const id of ids) {
  console.log(`\n=== ${id} ===`)
  const { outDir, sizes, totalJsBytes } = await buildApp({ id })
  const marker = MARKERS[id]
  const hasMarker = bundleContains(outDir, marker.needle)
  const aliasOk = hasMarker === marker.expect

  const smokeFile = join(RESULTS, `app-${id}.json`)
  const res = spawnSync('bun', [join(HERE, 'app-smoke.js'), outDir, smokeFile], {
    cwd: resolve(DIRS, '../..'),
    stdio: 'inherit',
    shell: process.platform === 'win32',
  })
  const smoke = existsSync(smokeFile) ? JSON.parse(readFileSync(smokeFile, 'utf8')) : null
  rows.push({
    id,
    aliasOk,
    marker: marker.needle,
    markerPresent: hasMarker,
    totalJsBytes,
    indexJsBytes: sizes['index.jsx'] || 0,
    bootMs: smoke?.bootMs ?? null,
    passed: smoke?.passed ?? 0,
    failed: smoke ? smoke.failed + (aliasOk ? 0 : 1) : 1,
    consoleErrors: smoke?.errors?.length ?? 0,
    smokeExit: res.status,
  })
}

const baseline = rows.find(r => r.id === 'baseline')
const pct = (v, base) => (v == null || !base ? '—' : `${v >= base ? '+' : ''}${(((v - base) / base) * 100).toFixed(1)}%`)

const aliasLabel = r => {
  const state = r.aliasOk ? 'ok' : 'WRONG'
  return `${state}: ${r.marker} ${r.markerPresent ? 'present' : 'absent'}`
}

const header = ['backend', 'bundle index.js', 'vs baseline', 'boot ms', 'app checks', 'alias proof', 'console.errors']
const line = cells => cells.map((c, i) => String(c).padEnd([28, 16, 12, 9, 17, 34, 15][i])).join('')
console.log(`\n=== real app (apps/repl) on each backend ===`)
console.log(line(header))
for (const r of rows) {
  console.log(
    line([
      r.id,
      `${(r.indexJsBytes / 1024).toFixed(1)} kB`,
      pct(r.indexJsBytes, baseline?.indexJsBytes),
      r.bootMs == null ? '—' : r.bootMs.toFixed(0),
      `${r.passed} pass / ${r.failed} fail`,
      aliasLabel(r),
      r.consoleErrors,
    ]),
  )
}

const md = []
md.push('# Real-app comparison — `apps/repl` on each backend')
md.push('')
md.push(`Generated by \`bun experiments/signal-directions/d-dual-surface/app-compare.js\` on ${new Date().toISOString()}.`)
md.push('')
md.push('The REPL is built **unmodified** with `@jsx6/signal` redirected to a candidate core by an')
md.push('esbuild resolve plugin, then booted headlessly and interrogated about what rendered. The')
md.push('`alias proof` column names the implementation-specific string literal searched for in the bundle:')
md.push('the baseline must **not** contain either marker, B must contain `signalStateChildren`, C must')
md.push('contain `signalAlienSource`. A wrong result fails the row.')
md.push('')
md.push('| backend | index.js | vs baseline | boot | app checks | alias proof | console.errors |')
md.push('|---|---|---|---|---|---|---|')
for (const r of rows) {
  md.push(
    `| \`${r.id}\` | ${(r.indexJsBytes / 1024).toFixed(1)} kB | ${pct(r.indexJsBytes, baseline?.indexJsBytes)} | ` +
      `${r.bootMs == null ? '—' : r.bootMs.toFixed(0) + ' ms'} | ${r.passed} / ${r.passed + r.failed} | ` +
      `${r.aliasOk ? 'ok' : '**WRONG**'} — \`${r.marker}\` ${r.markerPresent ? 'present' : 'absent'} | ${r.consoleErrors} |`,
  )
}
md.push('')
md.push('App checks asserted: bundle boots without throwing · static children rendered · a `Jsx6` class')
md.push('component and a function component rendered · `Loop` items set through the scope (`p` attribute) ·')
md.push('scope captured `editor`/`editor3` parts · `x-value` inputs present · `x-if` reacts to a signal')
md.push('write **synchronously** · a `Loop` re-renders after an async signal write · a **Promise used')
md.push('directly as a JSX child** resolves into the DOM.')
md.push('')
md.push(`Entries built: ${ENTRIES.join(', ')}. Full bundle totals are in each run's console output.`)
writeFileSync(OUT, md.join('\n'), 'utf8')
console.log(`\nwrote ${OUT}`)

if (serveId) {
  const outDir = join(BUILD_ROOT, serveId)
  // A plain static server rather than live-server: live-server injects its reload script into HTML
  // responses, and that response hung indefinitely in this environment (the JS/CSS served fine), which
  // would have made the "click through the REPL" step unusable. Bun.serve is dependency-free and
  // predictable; hot reload is not needed for eyeballing a swapped backend.
  const server = Bun.serve({
    port,
    hostname: '127.0.0.1',
    async fetch(req) {
      const url = new URL(req.url)
      const rel = url.pathname === '/' ? '/index.html' : url.pathname
      const file = join(outDir, rel)
      if (!file.startsWith(outDir)) return new Response('forbidden', { status: 403 })
      const body = Bun.file(file)
      if (!(await body.exists())) return new Response(`not found: ${rel}`, { status: 404 })
      return new Response(body)
    },
  })
  console.log(`\nserving ${serveId} → http://127.0.0.1:${server.port}/index.html`)
  console.log('open that URL, click through the REPL, then stop this process to shut the server down')
  // Bun.serve keeps the process alive; the comparison itself is already finished.
} else {
  process.exit(rows.some(r => r.failed) ? 1 : 0)
}