#!/usr/bin/env bun
/**
 * The comparison runner: runs the frozen contract **and** the benchmarks for every direction (plus the
 * untouched baseline) and writes one table to `RESULTS.md` and stdout.
 *
 *   bun experiments/signal-directions/harness/compare.js
 *   bun experiments/signal-directions/harness/compare.js baseline b-native-computed
 *
 * Each direction is measured in its own process (`bench-one.js`) so that JIT/GC state from one
 * implementation cannot contaminate the next. Contract results, capability matrix, micro/macro
 * timings, heap, dependency count and LOC all land in the same table, so a direction cannot look good
 * on one axis while quietly failing another.
 */

import { spawnSync } from 'child_process'
import { existsSync, readFileSync, writeFileSync } from 'fs'
import { join, resolve } from 'path'
import { fmtKb, fmtMs, pctVs } from './stats.js'

const HERE = import.meta.dir
const ROOT = resolve(HERE, '..')
const RESULTS_DIR = join(HERE, '.results')
const OUT = join(ROOT, 'RESULTS.md')

const requested = process.argv.slice(2)
const ids = requested.length
  ? requested
  : ['baseline', 'a-compat', 'b-native-computed', 'c-alien-backend', 'e-alien-native', 'f-bridge-hybrid']

const rows = []
for (const id of ids) {
  const outFile = join(RESULTS_DIR, `${id.replace('/', '_')}.json`)
  console.log(`\n--- measuring ${id} (own process) ---`)
  const res = spawnSync('bun', [join(HERE, 'bench-one.js'), id, outFile], {
    cwd: ROOT,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  })
  if (res.status !== 0 || !existsSync(outFile)) {
    rows.push({ id, error: `bench-one exited with ${res.status}` })
    continue
  }
  rows.push(JSON.parse(readFileSync(outFile, 'utf8')))
}

const baseline = rows.find(r => r.id === 'baseline' && !r.error)

const capNames = [
  'core',
  'union-deps',
  'computed',
  'computed:auto',
  'computed:dynamic-deps',
  'computed:eager',
  'computed:alien-only',
  'dispose',
  'batch',
  'batch:core',
  'interop',
  'interop:bridge-required',
  'interop:no-bridge-needed',
  'alien-surface',
]

const benchNames = [
  ['writeRead', 'write+read'],
  ['fanout', 'fanout×100'],
  ['chain', 'chain×4'],
  ['diamond', 'diamond'],
  ['computed', 'computed read'],
  ['churn', 'bind/unbind'],
  ['stateMerge', '$State merge'],
  ['batch', 'batch×2 writes'],
]

const short = id => id.slice(0, 12)
const lines = []
const md = []

lines.push('')
lines.push('=== contract ===')
lines.push(
  ['direction', 'pass', 'fail', 'skip', 'own LOC', '+shared', 'deps']
    .map((h, i) => h.padEnd([26, 5, 5, 5, 8, 8, 30][i]))
    .join(''),
)
for (const r of rows) {
  if (r.error) {
    lines.push(`${r.id.padEnd(26)} ERROR: ${r.error}`)
    continue
  }
  lines.push(
    [
      r.id.padEnd(26),
      String(r.passed).padEnd(5),
      String(r.failed).padEnd(5),
      String(r.skipped).padEnd(5),
      String(r.loc).padEnd(8),
      String(r.sharedLoc).padEnd(8),
      ((r.meta.deps || []).join(', ') || '—').slice(0, 28),
    ].join(''),
  )
}

lines.push('')
lines.push('=== capabilities ===')
lines.push(`  ${'capability'.padEnd(26)}${rows.map(r => short(r.id).padEnd(14)).join('')}`)
for (const cap of capNames) {
  lines.push(
    `  ${cap.padEnd(26)}${rows.map(r => ((r.meta?.capabilities || []).includes(cap) ? '✓' : '·').padEnd(14)).join('')}`,
  )
}

lines.push('')
lines.push('=== micro benchmarks (median ms, lower is better) ===')
lines.push(`  ${'bench'.padEnd(18)}${rows.map(r => short(r.id).padEnd(14)).join('')}`)
for (const [key, label] of benchNames) {
  lines.push(
    `  ${label.padEnd(18)}${rows.map(r => (r.error ? 'n/a' : fmtMs(r.micro[key])).padEnd(14)).join('')}`,
  )
}

lines.push('')
lines.push('=== micro benchmarks vs baseline ===')
for (const [key, label] of benchNames) {
  const cells = rows.map(r => {
    if (r.error || !r.micro || r.micro[key] == null || baseline?.micro?.[key] == null) return 'n/a'.padEnd(14)
    return (pctVs(r.micro[key], baseline.micro[key]) || '0%').padEnd(14)
  })
  lines.push(`  ${label.padEnd(18)}${cells.join('')}`)
}

lines.push('')
lines.push('=== long-lived components (300 mounted, 3000 writes, unmount) ===')
lines.push(`  ${'metric'.padEnd(20)}${rows.map(r => short(r.id).padEnd(14)).join('')}`)
for (const [key, label] of [
  ['mountMs', 'mount'],
  ['updateMs', 'updates'],
  ['unmountMs', 'unmount'],
  ['mountHeapKb', 'heap while up'],
  ['retainedHeapKb', 'heap retained'],
]) {
  lines.push(
    `  ${label.padEnd(20)}${rows
      .map(r => (r.error ? 'n/a' : key.endsWith('Kb') ? fmtKb(r.macro[key]) : fmtMs(r.macro[key])).padEnd(14))
      .join('')}`,
  )
}

console.log(lines.join('\n'))

// ------------------------------------------------------------------ RESULTS.md
md.push('# Direction comparison — measured results')
md.push('')
md.push(
  `Generated by \`bun experiments/signal-directions/harness/compare.js\` on ${new Date().toISOString()}.`,
)
md.push('')
md.push('Every direction is exercised through the frozen facade in `contract.md`, and each one is')
md.push('measured **in its own process** (`bench-one.js`) so JIT/GC state cannot leak between them.')
md.push('Benchmarks are medians of 5 runs after a discarded warm-up, on the machine that generated this')
md.push('file — treat the **relative** columns as the result, not the absolute milliseconds.')
md.push('')
md.push("`own LOC` counts the direction directory's JavaScript, excluding tests; `+shared` is the")
md.push("`_shared/` compat layer that A/E/F (and C's interop exports) reuse.")
md.push('')
md.push('## Contract')
md.push('')
md.push('| direction | pass | fail | skip | own LOC | +shared | dependencies |')
md.push('|---|---|---|---|---|---|---|')
for (const r of rows) {
  if (r.error) {
    md.push(`| ${r.id} | — | — | — | — | — | **could not run: ${r.error}** |`)
    continue
  }
  md.push(
    `| \`${r.id}\` | ${r.passed} | ${r.failed} | ${r.skipped} | ${r.loc} | ${r.sharedLoc} | ${(r.meta.deps || []).join(', ') || '—'} |`,
  )
}
md.push('')
md.push('## Capabilities')
md.push('')
md.push(`| capability | ${rows.map(r => r.id).join(' | ')} |`)
md.push(`|---|${rows.map(() => '---').join('|')}|`)
for (const cap of capNames) {
  md.push(
    `| \`${cap}\` | ${rows.map(r => ((r.meta?.capabilities || []).includes(cap) ? '✓' : '·')).join(' | ')} |`,
  )
}
md.push('')
md.push('## Micro benchmarks (median ms)')
md.push('')
md.push(`| bench | ${rows.map(r => r.id).join(' | ')} |`)
md.push(`|---|${rows.map(() => '---').join('|')}|`)
for (const [key, label] of benchNames) {
  md.push(`| ${label} | ${rows.map(r => (r.error ? 'n/a' : fmtMs(r.micro[key]))).join(' | ')} |`)
}
md.push('')
md.push('### Relative to the untouched baseline')
md.push('')
md.push(`| bench | ${rows.map(r => r.id).join(' | ')} |`)
md.push(`|---|${rows.map(() => '---').join('|')}|`)
for (const [key, label] of benchNames) {
  md.push(
    `| ${label} | ${rows
      .map(r =>
        r.error || !r.micro || r.micro[key] == null || baseline?.micro?.[key] == null
          ? 'n/a'
          : pctVs(r.micro[key], baseline.micro[key]) || '0%',
      )
      .join(' | ')} |`,
  )
}
md.push('')
md.push('## Long-lived components')
md.push('')
md.push(`| metric | ${rows.map(r => r.id).join(' | ')} |`)
md.push(`|---|${rows.map(() => '---').join('|')}|`)
for (const [key, label] of [
  ['mountMs', 'mount 300 (ms)'],
  ['updateMs', '3000 writes (ms)'],
  ['unmountMs', 'unmount (ms)'],
  ['mountHeapKb', 'heap while mounted (kB)'],
  ['retainedHeapKb', 'heap retained after unmount (kB)'],
]) {
  md.push(
    `| ${label} | ${rows
      .map(r => (r.error ? 'n/a' : key.endsWith('Kb') ? fmtKb(r.macro[key]) : fmtMs(r.macro[key])))
      .join(' | ')} |`,
  )
}
md.push('')
md.push('## Notes per direction')
md.push('')
for (const r of rows) {
  if (r.error) continue
  md.push(`### \`${r.id}\` — ${r.meta.name}`)
  md.push('')
  md.push(`* backend: ${r.meta.backend}`)
  md.push(`* capabilities: ${(r.meta.capabilities || []).join(', ') || '—'}`)
  md.push(`* dependencies: ${(r.meta.deps || []).join(', ') || '—'}`)
  if (r.meta.notes) md.push(`* ${r.meta.notes}`)
  if (r.failures?.length) {
    md.push('* failing contract cases:')
    for (const f of r.failures) md.push(`  * \`${f.id}\`: ${f.reason}`)
  }
  md.push('')
}

writeFileSync(OUT, md.join('\n'), 'utf8')
console.log(`\nwrote ${OUT}`)

const failures = rows.reduce((n, r) => n + (r.error ? 1 : 0) + (r.failed || 0), 0)
process.exit(failures ? 1 : 0)
