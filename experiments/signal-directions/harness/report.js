#!/usr/bin/env bun
/**
 * Generates `USAGE-AND-SIZE.md`: the same tasks solved in every direction, the measured bundle sizes,
 * and the executed interop matrix.
 *
 *   bun experiments/signal-directions/harness/report.js
 *
 * Nothing in the output is hand-written except the prose: task outcomes are executed, sizes are
 * bundled and gzipped, interop statuses are observed.
 */

import { writeFileSync } from 'fs'
import { join, resolve } from 'path'
import { runDirection } from './run.js'
import { runTasks, tasks } from './examples.js'
import { runInterop, probes, STATUS_ICON } from './interop.js'
import { measureAlienBaseline, measureAppEntries, measureSizes } from './size.js'

const HERE = import.meta.dir
const DIRS = resolve(HERE, '..')
const OUT = join(DIRS, 'USAGE-AND-SIZE.md')

const IDS = ['baseline', 'a-compat', 'b-native-computed', 'c-alien-backend', 'e-alien-native', 'f-bridge-hybrid']
const APPLY_IDS = ['baseline', 'b-native-computed', 'c-alien-backend']

const kb = n => `${(n / 1024).toFixed(1)} kB`
const short = id => id.replace('baseline', 'baseline').replace('-native-computed', '-native').replace('-alien-backend', '-alien')

// ------------------------------------------------------------------ collect
const per = {}
for (const id of IDS) {
  const { meta, api } = await runDirection(`../${id}/index.js`)
  per[id] = { meta, api, tasks: runTasks(api), interop: runInterop(api) }
}
const sizes = await measureSizes(IDS)
const alienSize = await measureAlienBaseline()
const appSizes = await measureAppEntries(APPLY_IDS)

const taskFailures = IDS.flatMap(id => per[id].tasks.filter(t => !t.ok).map(t => `${id}/${t.id}`))

// ------------------------------------------------------------------ document
const md = []
const w = l => md.push(l)

w('# Usage, size and interop — the measured comparison')
w('')
w(`Generated by \`bun experiments/signal-directions/harness/report.js\` on ${new Date().toISOString()}.`)
w('')
w('Three questions, all answered by execution rather than description:')
w('')
w('1. **Usage** — the same twelve tasks solved in each direction, so the code differences are visible')
w('   and the behavioural differences are measured.')
w('2. **Size** — plain, minified and gzipped bundles, for a small facade entry and for the real')
w('   `apps/repl` entry.')
w('3. **Interop** — what happens when alien-signals and jsx6 signals meet, per direction, including the')
w('   failure modes of the directions that need a bridge (or have none).')
w('')
w('## 1. Usage: the same tasks, per direction')
w('')
w('Each task shows the snippet a user writes. Where the snippet is identical across directions it is')
w('shown once; where it differs, each variant is shown with the outcome that was actually observed')
w('(all outcomes were executed — see the runner).')
w('')

for (const t of tasks) {
  w(`### ${t.id} — ${t.title}`)
  w('')
  w(`*${t.why}*`)
  w('')
  w('| direction | observed | expected | ok |')
  w('|---|---|---|---|')
  for (const id of IDS) {
    const r = per[id].tasks.find(x => x.id === t.id)
    w(`| \`${id}\` | \`${r.observed}\` | \`${r.expected}\` | ${r.ok ? '✓' : '**✗**'} |`)
  }
  w('')
  const shared = per[IDS[0]].tasks.find(x => x.id === t.id).shared
  if (shared) {
    w(`Identical in every direction (${IDS.length} of ${IDS.length}):`)
    w('')
    w('```js')
    w(per[IDS[0]].tasks.find(x => x.id === t.id).code)
    w('```')
  } else {
    w('Code per direction (only the variants that differ are shown as separate blocks):')
    w('')
    const seen = new Set()
    for (const id of IDS) {
      const r = per[id].tasks.find(x => x.id === t.id)
      if (seen.has(r.code)) continue
      seen.add(r.code)
      const group = IDS.filter(other => per[other].tasks.find(x => x.id === t.id).code === r.code)
      w(`**${group.map(g => `\`${g}\``).join(', ')}**`)
      w('')
      w('```js')
      w(r.code)
      w('```')
    }
  }
  w('')
}

w('## 2. Bundle size (plain / minified / gzipped)')
w('')
w('Measured by bundling a small entry with esbuild, then gzipping the minified output. Two entries,')
w('because both answers matter:')
w('')
w('* **core only** — `signal`, `$S`, `$F`, `$State`, `mergeValue`, `observeNow`, `observe`. What the')
w('  direction costs an app that never touches the new computed axis (tree-shaking included).')
w('* **with computed** — the same entry **plus** `$C`/`$CE`/`batch`/`dispose` (or, for the interop-only')
w('  directions, an alien `computed` used through the compat layer). A strict superset, so the')
w('  difference between the columns is the price of the computed axis.')
w('')
w('| direction | core plain | core min | core gzip | +computed min | +computed gzip | Δ min vs baseline | Δ gzip vs baseline |')
w('|---|---|---|---|---|---|---|---|')
const baseSize = sizes.find(s => s.id === 'baseline')
for (const s of sizes) {
  const dMin = s.core.minBytes - baseSize.core.minBytes
  const dGz = s.core.gzipBytes - baseSize.core.gzipBytes
  const pct = (d, b) => (b ? `${d >= 0 ? '+' : ''}${((d / b) * 100).toFixed(0)}%` : '—')
  w(
    `| \`${s.id}\` | ${kb(s.core.plainBytes)} | ${kb(s.core.minBytes)} | ${kb(s.core.gzipBytes)} | ` +
      `${s.computed ? kb(s.computed.minBytes) : 'n/a'} | ${s.computed ? kb(s.computed.gzipBytes) : 'n/a'} | ` +
      `${dMin >= 0 ? '+' : '−'}${kb(Math.abs(dMin))} (${pct(dMin, baseSize.core.minBytes)}) | ` +
      `${dGz >= 0 ? '+' : '−'}${kb(Math.abs(dGz))} (${pct(dGz, baseSize.core.gzipBytes)}) |`,
  )
}
w('')
w(`For reference, **alien-signals alone** (imported directly and used through ` +
  `\`signal\`/\`computed\`/\`effect\`/\`effectScope\`/\`trigger\`/\`startBatch\`) bundles to ` +
  `**${kb(alienSize.plainBytes)} plain / ${kb(alienSize.minBytes)} min / ${kb(alienSize.gzipBytes)} gzip**.`)
w('')
w('### The real application (`apps/repl`, `index.jsx` entry)')
w('')
w('| backend | plain | minified | gzip (of minified) | gzip (of plain) | vs baseline (min) |')
w('|---|---|---|---|---|---|')
const baseApp = appSizes.find(a => a.id === 'baseline')
for (const a of appSizes) {
  if (a.missing) {
    w(`| \`${a.id}\` | — | — | — | — | not built (run \`app-compare.js\`) |`)
    continue
  }
  const d = a.minBytes - baseApp.minBytes
  w(
    `| \`${a.id}\` | ${kb(a.plainBytes)} | ${kb(a.minBytes)} | ${kb(a.gzipBytes)} | ${kb(a.gzipPlainBytes)} | ` +
      `${d >= 0 ? '+' : '−'}${kb(Math.abs(d))} (${((d / baseApp.minBytes) * 100).toFixed(1)}%) |`,
  )
}
w('')
w('**Reading the size numbers:**')
w('')
w('* The interop-only directions (A/E/F) cost ~1.8 kB gzip in the *core-only* graph even if the app')
w('  never interops, because `_shared/alien-compat.js` imports alien statically. Making that import')
w('  lazy (or moving it to its own subpath) would keep a non-interop app at baseline size — a concrete,')
w('  cheap improvement if A/E/F are chosen.')
w('* B costs **+0.8 kB gzip** over the baseline for the whole computed/batching/tracking axis, because')
w('  it has no dependency to pull in. It is the cheapest direction by a wide margin.')
w('* C costs **+2.8 kB gzip** in the core graph and **+2.3 kB gzip** in the real app: alien is')
w('  ~1.8 kB gzip of that, and it cannot be tree-shaken away because the storage layer is alien.')
w('* E/F cost the same as C in the core graph (~3.7–3.8 kB gzip) while providing less (no eager mode,')
w('  no dispose of computeds) — their value is opt-in adoption, not size.')
w('')

w('## 3. Interop with alien-signals: possibilities, ergonomics, failure modes')
w('')
w('Executed probe matrix. `native` = the direction’s own signals are alien nodes (no bridge at all);')
w('`bridged` = works through `toAlien`/`toSignal` or automatic dependency normalisation;')
w('`needs-bridge` = works only if the caller bridges, otherwise silently stale; `static`/`stale` = it')
w('does not work and does **not** throw.')
w('')
w(`| probe | ${IDS.map(id => `\`${short(id)}\``).join(' | ')} |`)
w(`|---|${IDS.map(() => '---').join('|')}|`)
for (const [pid, title] of probes) {
  const cells = IDS.map(id => {
    const r = per[id].interop.find(x => x.id === pid)
    return STATUS_ICON[r.status] || r.status
  })
  w(`| **${pid}** ${title} | ${cells.join(' | ')} |`)
}
w('')
w('### Evidence and ergonomics, probe by probe')
w('')
for (const [pid, title] of probes) {
  w(`**${pid} — ${title}**`)
  w('')
  for (const id of IDS) {
    const r = per[id].interop.find(x => x.id === pid)
    w(`* \`${id}\`: ${STATUS_ICON[r.status]} — ${r.evidence}`)
  }
  w('')
}

w('### What the interop probes mean in practice')
w('')
w('**Which directions need a bridge, and which do not**')
w('')
w('* **C needs none.** Its `prepareSignal` stores the value in an `alien.signal`, so a bare jsx6 read')
w('  inside an alien `computed`/`effect` registers a dependency natively (P1), and `toAlien($sig)` is a')
w('  zero-allocation lookup of the backing node rather than a listener bridge (P9). This is C’s one')
w('  structural advantage over every other direction.')
w('* **A, E and F need a bridge** for every value that crosses (P1/P3/P6 all report `needs-bridge`),')
w('  because their signals are the original closure-backed ones.')
w('* **The baseline and B have no bridge at all** — not even a helper. A user with alien in the app can')
w('  still hand an alien node to jsx6 code, and that is where the two silent failure modes appear.')
w('')
w('**The two silent failure modes (no exception, wrong result)**')
w('')
w('1. **Alien node handed to a jsx6 derived signal** (P4/T10): the untouched `$F`/`$S` decide')
w('   “derived vs static” with their own `isObservable`, which does not know alien nodes, so the alien')
w('   node is treated as a *static value*. `$F(v => v * 2, alienSignal)` returns the alien node itself')
w('   — the derived signal holds a function, and the UI renders the function. Compat fixes this by')
w('   normalising the dependency list (`toSignal` mirrors) before delegating; C fixes it by extending')
w('   its own `isObservable` to accept alien nodes.')
w('2. **Alien node used where JSX expects a signal** (P5/T11): `insertAttr` and `nodeFromObservable`')
w('   treat any function value as a signal and call `observeNow` on it. With no alien-aware branch the')
w('   updater receives the function itself and runs once — `{$computed}` renders source instead of a')
w('   number. This is the single most user-visible interop bug, and it is why A/E/F/C all override')
w('   `observe`/`observeNow`/`subscribe`/`isObservable` rather than only adding `toAlien`.')
w('')
w('**Bridge ergonomics, honestly**')
w('')
w('* **Direction of travel matters.** Bridging jsx6 → alien is a *listener* (one alien signal + one')
w('  `subscribeSymbol` registration per source). Bridging alien → jsx6 is an *effect* (one root alien')
w('  effect per node, which is what keeps the mirror hot). Both are cached, so calling `toAlien($a)`')
w('  twice returns the same node (P9), and repeated `toSignal(node)` returns the same mirror.')
w('* **Batching is not implied.** `batch()` in A/E/F defers only the alien effect queue, so a two-write')
w('  update still notifies the *core* graph twice (T7). Anyone bridging expects `batch` to make the')
w('  combined update atomic; it does not. This is the most surprising ergonomic gap in A/E/F.')
w('* **Tracking is not transitive by accident.** An unbridged read inside an alien `computed` is just a')
w('  function call: no dependency, no update, no warning (P1/T9). The rule a user must internalise is')
w('  “alien sees only alien values; bridge at the boundary” — which is easy to state and easy to forget')
w('  in a JSX prop.')
w('* **Disposal is a third disposal mechanism.** A mirror or bridge owns an effect or a listener that')
w('  must be released (`dispose(node)`), on top of the core’s `observeNow` unsubscribe and, in C, the')
w('  computed’s push effect. Long-lived components make this the main risk of any interop direction, and')
w('  it is why `dispose` was kept as a first-class export rather than an internal detail.')
w('* **Ergonomic cost can be removed cheaply.** Two concrete improvements if an interop direction is')
w('  chosen: (a) make the alien import lazy so non-interop apps do not pay its ~1.8 kB gzip; (b) accept')
w('  a plain jsx6 signal in a JSX-visible position by auto-bridging inside `observeNow`, instead of')
w('  requiring an explicit `toAlien()` call at every crossing.')
w('')

w('## 4. Task outcomes that differ from the expectation')
w('')
if (taskFailures.length) {
  w('These are mismatches between observed behaviour and the expectation encoded in the runner — each')
  w('one is either a bug in a direction or a wrong expectation:')
  w('')
  for (const id of IDS) {
    for (const t of per[id].tasks.filter(t => !t.ok)) {
      w(`* \`${id}\` / \`${t.id}\`: observed \`${t.observed}\`, expected \`${t.expected}\``)
    }
  }
} else {
  w('None — every task produced the expected outcome in every direction.')
}
w('')

writeFileSync(OUT, md.join('\n'), 'utf8')
console.log(`wrote ${OUT}`)
console.log(`tasks: ${IDS.length * tasks.length} executions, ${taskFailures.length} unexpected`)
process.exit(taskFailures.length ? 1 : 0)